"""Generates web/src/tokens.css from web/src/tokens.json.

Theme selection (no flash of the wrong theme: the server renders
data-theme on <html> from the user's choice):
  :root                                   light
  prefers-color-scheme: dark, no override dark
  [data-theme=dark]                       dark
  prefers-contrast: more                  the high-contrast variant of the above

Usage: build_tokens.py [--check] [ROOT]
  --check  fail if tokens.css is not up to date instead of writing it.
"""
import json
import sys
from pathlib import Path

HEADER = """/* SPDX-FileCopyrightText: 2026 Erich Seifert <dev@erichseifert.de> */
/* SPDX-License-Identifier: AGPL-3.0-or-later */
/* Generated by scripts/build_tokens.py from tokens.json. Do not edit. */
"""


def block(selector: str, values: dict[str, str], indent: str = "") -> str:
    lines = [f"{indent}{selector} {{"]
    lines += [f"{indent}  --{k}: {v};" for k, v in values.items()]
    lines.append(f"{indent}}}")
    return "\n".join(lines)


def render(doc: dict) -> str:
    c = doc["colors"]
    out = [HEADER]
    out.append(block(":root", {**doc["tokens"], **c["light"]}).replace(":root {", ":root {\n  color-scheme: light dark;", 1))
    for name, values in doc.get("density", {}).items():
        out.append(block(f':root[data-density="{name}"]', values))
    # The user's code font size (12-20 px), independent of the UI scale.
    lo, hi = doc.get("code-size-range", [12, 20])
    for px in range(lo, hi + 1):
        out.append(block(f':root[data-code-size="{px}"]', {"code-size": f"{px / 16:g}rem"}))
    # Coarse pointers get 44 px targets in every density.
    if "coarse" in doc:
        out.append("@media (pointer: coarse) {\n" + block(":root,\n  :root[data-density]", doc["coarse"], "  ") + "\n}")
    out.append(':root[data-theme="light"] {\n  color-scheme: light;\n}')
    out.append(':root[data-theme="dark"] {\n  color-scheme: dark;\n}')
    out.append("@media (prefers-color-scheme: dark) {\n" + block(':root:not([data-theme="light"])', c["dark"], "  ") + "\n}")
    out.append(block(':root[data-theme="dark"]', c["dark"]))
    out.append(
        "@media (prefers-contrast: more) {\n"
        + block(":root", c["light-hc"], "  ")
        + "\n  @media (prefers-color-scheme: dark) {\n"
        + block(':root:not([data-theme="light"])', c["dark-hc"], "    ")
        + "\n  }\n"
        + block(':root[data-theme="dark"]', c["dark-hc"], "  ")
        + "\n}"
    )
    out.append("@media (prefers-reduced-motion: reduce) {\n  :root {\n    --motion-fast: 0ms;\n    --motion-normal: 0ms;\n  }\n}")
    return "\n\n".join(out) + "\n"


def main(argv: list[str]) -> int:
    check = "--check" in argv
    args = [a for a in argv if not a.startswith("--")]
    root = Path(args[0]) if args else Path(__file__).resolve().parent.parent
    doc = json.loads((root / "web/src/tokens.json").read_text(encoding="utf-8"))
    sets = list(doc["colors"])
    names = set(doc["colors"]["light"])
    for s in sets:
        if set(doc["colors"][s]) != names:
            print(f"tokens: color set {s} doesn't define the same tokens as light: {sorted(set(doc['colors'][s]) ^ names)}", file=sys.stderr)
            return 1
    css = render(doc)
    target = root / "web/src/tokens.css"
    if check:
        if not target.exists() or target.read_text(encoding="utf-8") != css:
            print("tokens: web/src/tokens.css is out of date; run `just tokens`", file=sys.stderr)
            return 1
        print("tokens: ok")
        return 0
    target.write_text(css, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
